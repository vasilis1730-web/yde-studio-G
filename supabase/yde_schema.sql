create or replace function public.yde_set_updated_at()
returns trigger language plpgsql set search_path=public
as $$ begin new.updated_at=now(); return new; end; $$;

drop trigger if exists yde_profiles_set_updated_at on public.yde_profiles;
create trigger yde_profiles_set_updated_at before update on public.yde_profiles
for each row execute procedure public.yde_set_updated_at();
drop trigger if exists yde_projects_set_updated_at on public.yde_projects;
create trigger yde_projects_set_updated_at before update on public.yde_projects
for each row execute procedure public.yde_set_updated_at();

create or replace function public.yde_prevent_owner_change()
returns trigger language plpgsql set search_path=public
as $$
begin
  if old.owner_id is distinct from new.owner_id and not public.yde_is_admin() then
    raise exception 'Δεν επιτρέπεται αλλαγή ιδιοκτήτη έργου';
  end if;
  return new;
end;
$$;
drop trigger if exists yde_projects_prevent_owner_change on public.yde_projects;
create trigger yde_projects_prevent_owner_change before update of owner_id on public.yde_projects
for each row execute procedure public.yde_prevent_owner_change();

alter table public.yde_profiles enable row level security;
alter table public.yde_projects enable row level security;
alter table public.yde_project_members enable row level security;
alter table public.yde_project_versions enable row level security;
alter table public.yde_audit_log enable row level security;

-- Αφαίρεση της παλιάς ανοικτής πολιτικής και επαναδημιουργία ασφαλών πολιτικών
DROP POLICY IF EXISTS yde_anon_all ON public.yde_projects;
DROP POLICY IF EXISTS yde_profiles_select ON public.yde_profiles;
DROP POLICY IF EXISTS yde_profiles_admin_insert ON public.yde_profiles;
DROP POLICY IF EXISTS yde_profiles_admin_update ON public.yde_profiles;
DROP POLICY IF EXISTS yde_profiles_admin_delete ON public.yde_profiles;
DROP POLICY IF EXISTS yde_projects_select ON public.yde_projects;
DROP POLICY IF EXISTS yde_projects_insert ON public.yde_projects;
DROP POLICY IF EXISTS yde_projects_update ON public.yde_projects;
DROP POLICY IF EXISTS yde_projects_delete ON public.yde_projects;
DROP POLICY IF EXISTS yde_members_select ON public.yde_project_members;
DROP POLICY IF EXISTS yde_members_manage ON public.yde_project_members;
DROP POLICY IF EXISTS yde_versions_select ON public.yde_project_versions;
DROP POLICY IF EXISTS yde_versions_insert ON public.yde_project_versions;
DROP POLICY IF EXISTS yde_audit_select ON public.yde_audit_log;
DROP POLICY IF EXISTS yde_audit_insert ON public.yde_audit_log;

create policy yde_profiles_select on public.yde_profiles for select to authenticated
using(id=auth.uid() or public.yde_is_admin());
create policy yde_profiles_admin_insert on public.yde_profiles for insert to authenticated
with check(public.yde_is_admin());
create policy yde_profiles_admin_update on public.yde_profiles for update to authenticated
using(public.yde_is_admin()) with check(public.yde_is_admin());
create policy yde_profiles_admin_delete on public.yde_profiles for delete to authenticated
using(public.yde_is_admin() and id<>auth.uid());

create policy yde_projects_select on public.yde_projects for select to authenticated
using(public.yde_can_view_project(id));
create policy yde_projects_insert on public.yde_projects for insert to authenticated
with check(public.yde_is_editor() and (owner_id=auth.uid() or public.yde_is_admin()));
create policy yde_projects_update on public.yde_projects for update to authenticated
using(public.yde_can_edit_project(id)) with check(public.yde_can_edit_project(id));
create policy yde_projects_delete on public.yde_projects for delete to authenticated
using(public.yde_is_admin() or (public.yde_is_editor() and owner_id=auth.uid()));

create policy yde_members_select on public.yde_project_members for select to authenticated
using(user_id=auth.uid() or public.yde_can_view_project(project_id));
create policy yde_members_manage on public.yde_project_members for all to authenticated
using(public.yde_is_admin() or exists(select 1 from public.yde_projects p where p.id=project_id and p.owner_id=auth.uid()))
with check(public.yde_is_admin() or exists(select 1 from public.yde_projects p where p.id=project_id and p.owner_id=auth.uid()));

create policy yde_versions_select on public.yde_project_versions for select to authenticated
using(public.yde_can_view_project(project_id));
create policy yde_versions_insert on public.yde_project_versions for insert to authenticated
with check(public.yde_can_edit_project(project_id) and owner_id=auth.uid());

create policy yde_audit_select on public.yde_audit_log for select to authenticated
using(user_id=auth.uid() or public.yde_is_admin());
create policy yde_audit_insert on public.yde_audit_log for insert to authenticated
with check(public.yde_is_active_user() and user_id=auth.uid());

revoke all on public.yde_profiles from anon;
revoke all on public.yde_projects from anon;
revoke all on public.yde_project_members from anon;
revoke all on public.yde_project_versions from anon;
revoke all on public.yde_audit_log from anon;
grant select on public.yde_profiles to authenticated;
grant select,insert,update,delete on public.yde_projects to authenticated;
grant select,insert,update,delete on public.yde_project_members to authenticated;
grant select,insert on public.yde_project_versions to authenticated;
grant select,insert on public.yde_audit_log to authenticated;
grant usage,select on all sequences in schema public to authenticated;

