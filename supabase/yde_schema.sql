create policy yde_storage_select on storage.objects for select to authenticated
using(bucket_id='yde-documents' and public.yde_is_active_user() and (public.yde_is_admin() or (storage.foldername(name))[1]=auth.uid()::text));
create policy yde_storage_insert on storage.objects for insert to authenticated
with check(bucket_id='yde-documents' and public.yde_is_editor() and (storage.foldername(name))[1]=auth.uid()::text);
create policy yde_storage_update on storage.objects for update to authenticated
using(bucket_id='yde-documents' and public.yde_is_editor() and (public.yde_is_admin() or (storage.foldername(name))[1]=auth.uid()::text))
with check(bucket_id='yde-documents' and public.yde_is_editor() and (public.yde_is_admin() or (storage.foldername(name))[1]=auth.uid()::text));
create policy yde_storage_delete on storage.objects for delete to authenticated
using(bucket_id='yde-documents' and public.yde_is_editor() and (public.yde_is_admin() or (storage.foldername(name))[1]=auth.uid()::text));

