begin;

create table if not exists public.yde_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text not null default '',
  specialty text not null default '',
  license_number text not null default '',
  role text not null default 'engineer' check (role in ('admin','engineer','viewer')),
  active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_login_at timestamptz
);

create table if not exists public.yde_projects (
  id text primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null default 'Νέο έργο ΥΔΕ',
  supply_number text not null default '',
  installation_type text not null default '',
  project_status text not null default 'draft' check (project_status in ('draft','finalized','archived')),
  data jsonb not null default '{}'::jsonb,
  revision integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists yde_projects_owner_idx on public.yde_projects(owner_id);
create index if not exists yde_projects_updated_idx on public.yde_projects(updated_at desc);

create table if not exists public.yde_project_members (
  project_id text not null references public.yde_projects(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  permission text not null default 'view' check (permission in ('view','edit')),
  created_at timestamptz not null default now(),
  primary key (project_id,user_id)
);
create index if not exists yde_project_members_user_idx on public.yde_project_members(user_id);

create table if not exists public.yde_project_versions (
  id bigint generated by default as identity primary key,
  project_id text not null references public.yde_projects(id) on delete cascade,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  revision integer not null,
  snapshot jsonb not null,
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists yde_project_versions_project_idx on public.yde_project_versions(project_id,created_at desc);

create table if not exists public.yde_audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  project_id text,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists yde_audit_log_user_idx on public.yde_audit_log(user_id,created_at desc);

create or replace function public.yde_is_active_user()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.yde_profiles p where p.id=auth.uid() and p.active=true); $$;

create or replace function public.yde_is_editor()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.yde_profiles p where p.id=auth.uid() and p.active=true and p.role in ('admin','engineer')); $$;

create or replace function public.yde_is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.yde_profiles p where p.id=auth.uid() and p.active=true and p.role='admin'); $$;

create or replace function public.yde_can_view_project(p_project_id text)
returns boolean language sql stable security definer set search_path=public
as $$
  select public.yde_is_active_user() and (
    public.yde_is_admin()
    or exists(select 1 from public.yde_projects p where p.id=p_project_id and p.owner_id=auth.uid())
    or exists(select 1 from public.yde_project_members m where m.project_id=p_project_id and m.user_id=auth.uid())
  );
$$;

create or replace function public.yde_can_edit_project(p_project_id text)
returns boolean language sql stable security definer set search_path=public
as $$
  select public.yde_is_editor() and (
    public.yde_is_admin()
    or exists(select 1 from public.yde_projects p where p.id=p_project_id and p.owner_id=auth.uid())
    or exists(select 1 from public.yde_project_members m where m.project_id=p_project_id and m.user_id=auth.uid() and m.permission='edit')
  );
$$;

revoke all on function public.yde_is_active_user() from public;
revoke all on function public.yde_is_editor() from public;
revoke all on function public.yde_is_admin() from public;
revoke all on function public.yde_can_view_project(text) from public;
revoke all on function public.yde_can_edit_project(text) from public;
grant execute on function public.yde_is_active_user() to authenticated;
grant execute on function public.yde_is_editor() to authenticated;
grant execute on function public.yde_is_admin() to authenticated;
grant execute on function public.yde_can_view_project(text) to authenticated;
grant execute on function public.yde_can_edit_project(text) to authenticated;

create or replace function public.handle_new_yde_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  insert into public.yde_profiles(id,email,full_name,active,role)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name',''),false,'engineer')
  on conflict(id) do update set email=excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_yde on auth.users;
create trigger on_auth_user_created_yde after insert or update of email on auth.users
for each row execute procedure public.handle_new_yde_user();

